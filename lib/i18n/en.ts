type WidenStrings<T> = T extends string
  ? string
  : { [K in keyof T]: WidenStrings<T[K]> };

/**
 * The English dictionary is the source of truth for key shape, but translation
 * values must stay assignable from other locales. Using `typeof en` directly
 * would preserve string literal types and reject every French translation.
 */
